import type { ReactNode } from 'react';
import { DECISION_TEXT } from '@/lib/api';

export function Container({ children, className = '' }: { children: ReactNode; className?: string }) {
  return <div className={`mx-auto max-w-[1240px] px-4 sm:px-6 ${className}`}>{children}</div>;
}

export function PageHead({ title, lede, children }: { title: string; lede?: ReactNode; children?: ReactNode }) {
  return (
    <Container className="pb-8 pt-14 sm:pt-20">
      <h1 className="t-h1 max-w-[22ch]">{title}</h1>
      {lede && <p className="t-lede mt-5 max-w-[62ch]">{lede}</p>}
      {children}
    </Container>
  );
}

export function Decision({ d, size = 'md' }: { d: string; size?: 'md' | 'lg' }) {
  const m = DECISION_TEXT[d] ?? { label: d, color: '#8796A3', plain: '' };
  return (
    <span className={`inline-flex items-center gap-2 rounded-full border font-semibold ${size === 'lg' ? 'px-4 py-1.5 text-lg' : 'px-2.5 py-0.5 text-sm'}`}
      style={{ borderColor: m.color + '66', color: m.color, background: m.color + '12' }}>
      <span className="h-1.5 w-1.5 rounded-full" style={{ background: m.color }} aria-hidden />
      {m.label}
    </span>
  );
}

const LABEL_STYLE: Record<string, string> = {
  SYNTHETIC: 'border-challenge/40 text-challenge',
  PRERECORDED: 'border-veto/40 text-veto',
  REAL: 'border-ok/40 text-ok',
};
export function DataLabel({ label, note }: { label: string; note?: string }) {
  return (
    <span className={`inline-flex items-center gap-1.5 rounded border px-1.5 py-0.5 text-xs font-medium ${LABEL_STYLE[label] ?? 'border-rule2 text-muted'}`}
      title={label === 'SYNTHETIC' ? 'Generated by the NeuroAssist simulator' : label === 'PRERECORDED' ? 'Exported file of unverified origin' : 'Captured by a NeuroAssist camera session'}>
      {label === 'SYNTHETIC' ? 'Synthetic' : label === 'PRERECORDED' ? 'Prerecorded, unverified' : 'Real measurement'}
      {note && <span className="text-muted">{note}</span>}
    </span>
  );
}

export function Notice({ tone = 'info', children }: { tone?: 'info' | 'error' | 'warn'; children: ReactNode }) {
  const c = tone === 'error' ? 'border-veto/50 text-veto' : tone === 'warn' ? 'border-challenge/40 text-challenge' : 'border-rule2 text-muted';
  return <div role={tone === 'error' ? 'alert' : 'status'} className={`rounded-lg border px-4 py-3 text-sm ${c}`}>{children}</div>;
}

export function Num({ v, d = 2, unit, sign = true }: { v: number | null | undefined; d?: number; unit?: string; sign?: boolean }) {
  if (v === null || v === undefined || !Number.isFinite(v)) return <span className="readout text-faint">n/a</span>;
  const s = (sign && v > 0 ? '+' : '') + v.toFixed(d);
  return <span className="readout">{s}{unit && <span className="ml-1 text-muted">{unit}</span>}</span>;
}

export function Section({ title, children, id, aside }: { title: string; children: ReactNode; id?: string; aside?: ReactNode }) {
  return (
    <section id={id} className="border-t border-rule">
      <Container className="grid gap-8 py-14 lg:grid-cols-[minmax(0,320px)_1fr]">
        <div>
          <h2 className="t-h2 max-w-[18ch]">{title}</h2>
          {aside && <div className="t-small mt-3 max-w-[36ch]">{aside}</div>}
        </div>
        <div className="min-w-0">{children}</div>
      </Container>
    </section>
  );
}
